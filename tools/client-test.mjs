import assert from 'node:assert/strict';
import { connect, offsetOf, uploadFile } from '../web/client.mjs';
const [base,key,other]=process.argv.slice(2);
const nativeFetch=globalThis.fetch;
globalThis.fetch=(path,options)=>nativeFetch(new URL(path,base),options);
assert.equal((await connect(key)).owner,'alice');
const file=new File([Buffer.alloc(3*1024*1024,'q')],'client-test.bin',{lastModified:123456});
const controller=new AbortController();
let session;
await assert.rejects(uploadFile(file,{key,signal:controller.signal,onSession:s=>session=s,onProgress:n=>{if(n>0&&n<file.size)controller.abort();}}));
assert.equal(await offsetOf(session.path,key),1024*1024);
await assert.rejects(uploadFile(file,{key:other,session}),/原用户/);
await assert.rejects(uploadFile(new File(['bad'],'other.bin'),{key,session}),/同一个文件/);
await assert.rejects(offsetOf('https://example.org/files/1',key),/无效的上传地址/);
assert.equal(await offsetOf(session.path,key),1024*1024);
await uploadFile(file,{key,session});
assert.equal(await offsetOf(session.path,key),file.size);
const response=await fetch(session.path+'/content',{headers:{Authorization:`Bearer ${key}`}});
assert.equal(response.status,200);
assert.deepEqual(Buffer.from(await response.arrayBuffer()),Buffer.alloc(file.size,'q'));
console.log(JSON.stringify({passed:true,cases:['pause','resume','owner mismatch','file mismatch','external URL rejected','download bytes']}));
